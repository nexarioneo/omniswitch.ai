interface SidebarProps {
  onNavigate?: () => void;
  onClose?: () => void;
  className?: string;
}

export function Sidebar({ onNavigate, onClose, className = "" }: SidebarProps) {
  const pathname = usePathname();
  const [gatewayName, setGatewayName] = useState("Omniswitch AI");

  useEffect(() => {
    fetch("/api/admin/settings")
      .then((res) => (res.ok ? res.json() : null))
      .then((data) => {
        if (data?.data?.gateway_name) setGatewayName(data.data.gateway_name);
      })
      .catch(() => {});
  }, []);

  return (
    <aside className={`w-70 bg-surface border-r border-outline-variant flex flex-col ${className}`}>
      <div className="h-16 flex items-center justify-between gap-2 px-4 md:px-6 border-b border-outline-variant">
        <span className="text-lg font-semibold text-on-surface truncate">{gatewayName}</span>
        {onClose && (
          <button
            type="button"
            onClick={onClose}
            aria-label="Close navigation"
            className="md:hidden inline-flex h-12 w-12 shrink-0 items-center justify-center rounded-full text-on-surface-variant hover:bg-on-surface/8"
          >
            <svg className="w-5 h-5" fill="none" stroke="currentColor" strokeWidth={1.5} strokeLinecap="round" strokeLinejoin="round" viewBox="0 0 24 24" aria-hidden="true">
              <path d="M6 6l12 12M18 6L6 18" />
            </svg>
          </button>
        )}
      </div>
      <nav className="flex-1 overflow-y-auto py-4">
        {navItems.map((item) => {
          const isActive =
            item.href === "/admin"
              ? pathname === "/admin"
              : pathname === item.href || pathname.startsWith(`${item.href}/`);
          return (
            <Link
              key={item.href}
              href={item.href}
              onClick={onNavigate}
              className={`flex items-center gap-3 mx-3 px-4 h-12 rounded-full text-sm font-medium transition-colors focus-visible:outline-2 focus-visible:outline-primary ${
                isActive
                  ? "bg-secondary-container text-on-secondary-container"
                  : "text-on-surface-variant hover:bg-on-surface/8"
              }`}
            >
              <svg className="w-5 h-5 shrink-0" fill="none" stroke="currentColor" strokeWidth={1.5} strokeLinecap="round" strokeLinejoin="round" viewBox="0 0 24 24" aria-hidden="true">
                <path d={item.icon} />
              </svg>
              {item.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}
